def meander_cdf(u: float, K: int = 60) -> float:
    """P(U <= u) for the maximum U of a Brownian meander on [0, 1]: 1 + 2 sum (-1)^k exp(-k^2 u^2 / 2),
    or, for small u, its Jacobi-transformed form (2 sqrt(2 pi) / u) sum_k exp(-(2k+1)^2 pi^2 / (2 u^2))."""
    if u <= 0:
        return 0.0
    if u < 1.0:
        k = np.arange(K)
        return float(2.0 * SQ2PI / u * np.sum(np.exp(-((2 * k + 1) ** 2) * math.pi ** 2 / (2.0 * u * u))))
    k = np.arange(1, K + 1)
    return float(1.0 + 2.0 * np.sum((-1.0) ** k * np.exp(-(k ** 2) * u * u / 2.0)))


def meander_mean() -> float:
    return integrate.quad(lambda u: 1.0 - meander_cdf(u), 0.0, 12.0, limit=400, epsabs=1e-13)[0]


def psi(a):
    """E[(Z - a)^+] = phi(a) - a Phibar(a)."""
    return norm.pdf(a) - a * norm.sf(a)


def gamma_tr(s: float) -> float:
    """First-order loading of TR^2/(4 ln 2): 1/4 + s/(4 pi ln 2) - I(s)/(2 sqrt(2 pi) ln 2), where
    I(s) = int_0^inf Phibar(u/s) P(U > u) du."""
    if s <= 0:
        return 0.25
    # I(s) = int_0^inf Phibar(u/s) P(U > u) du: for s < 1 integrate in v = u/s, so that the narrow
    # factor Phibar(u/s) is resolved; for s >= 1 in u, where the narrow factor is P(U > u)
    if s < 1.0:
        I = s * integrate.quad(lambda v: norm.sf(v) * (1.0 - meander_cdf(s * v)), 0.0, 40.0, limit=400,
                               epsabs=1e-14)[0]
    else:
        I = integrate.quad(lambda u: norm.sf(u / s) * (1.0 - meander_cdf(u)), 0.0, 12.0, limit=400,
                           epsabs=1e-14)[0]
    return 0.25 + s / (4.0 * math.pi * LN2) - I / (2.0 * SQ2PI * LN2)


def gamma_tr_direct(s: float) -> float:
    """The same loading from its definition, 1/4 + s E[psi(U/s)] / (2 sqrt(2 pi) ln 2), integrating psi
    against the meander density (a second numerical route)."""
    dens = lambda u: (meander_cdf(u + 1e-5) - meander_cdf(u - 1e-5)) / 2e-5
    E = integrate.quad(lambda u: psi(u / s) * dens(u), 1e-4, 12.0, limit=600, epsabs=1e-12)[0]
    return 0.25 + s * E / (2.0 * SQ2PI * LN2)


def meander_cdf_from_images(x: float, a: float = 1e-4) -> float:
    """P(-m <= x | M < a) for small a, from the method-of-images series: the meander limit of the
    supplement's equation (G)."""
    return p_max_min(a, x) / (2.0 * norm.cdf(a) - 1.0)


# =============================================================================================
# The kernels on simulated bars (Assumption 2, with o* ~ N(0, s^2) and sigma_c = 1)
# =============================================================================================

def kernels(ostar, eta, M, m, D, s, rho, lam0=LAM0):
    """Each kernel on the printed bar, and on the bar without the error, per draw."""
    o = ostar + eta
    h, l = ostar + np.maximum(eta, M), ostar + np.minimum(eta, m)
    he, le = ostar + M, ostar + m
    r = ostar + D
    b = s * s / (s * s + rho * rho)
    w = lam0 * (1.0 - b)
    R, Re = h - l, M - m
    TR, TRe = np.maximum(h, 0) - np.minimum(l, 0), np.maximum(he, 0) - np.minimum(le, 0)
    Rs = np.maximum(h, b * o) - np.minimum(l, b * o)
    P, Pe = R ** 2 / (4 * LN2), Re ** 2 / (4 * LN2)
    TP, TPe = TR ** 2 / (4 * LN2), TRe ** 2 / (4 * LN2)
    full = (1 - w) * ((b * o) ** 2 + Rs ** 2 / (4 * LN2)) + w * r * r
    post = (1 - w) * (b * b * o * o + b * (1 - b) * (s * s + rho * rho) + Rs ** 2 / (4 * LN2)) + w * r * r
    clean = ostar ** 2 + Pe                                  # every full-type kernel when the open is exact
    return {
        "close-to-close r^2": (r * r, r * r),
        "Parkinson": (P, Pe),
        "true-range Parkinson TR^2/(4 ln 2)": (TP, TPe),
        "open-free kernel": ((1 - lam0) * TP + lam0 * r * r, (1 - lam0) * TPe + lam0 * r * r),
        "full kernel": (full, clean),
        "full kernel, posterior overnight term": (post, clean),
        "overnight^2 + Parkinson": (o * o + P, clean),
    }


FIRST_ORDER = {"close-to-close r^2": lambda s: 0.0, "Parkinson": lambda s: 0.5,
               "true-range Parkinson TR^2/(4 ln 2)": gamma_tr, "open-free kernel": lambda s: (1 - LAM0) * gamma_tr(s),
               "full kernel": lambda s: -0.5, "full kernel, posterior overnight term": lambda s: 0.5,
               "overnight^2 + Parkinson": lambda s: 1.5}


