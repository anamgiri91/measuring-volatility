def part_a(L: Ledger, N: Numbers, n: int, steps: int, rng) -> dict:
    P = "7"
    # (a) the overnight term -------------------------------------------------------------------
    for s, t in ((1.0, 0.8), (0.5, 1.2), (2.0, 0.5)):
        os_ = rng.normal(0, s, n)
        o = os_ + rng.normal(0, t, n)
        b = s * s / (s * s + t * t)
        m2 = s * s + t * t
        v, se = batch_mean((b * o) ** 2 - b * os_ ** 2)
        L.mc(P, "a: E[(b o)^2] = b E[o*^2] under an uncorrelated error", f"s={s}, sigma_eta={t}", 0.0, v, se)
        v, se = batch_mean(b * b * o * o + b * (1 - b) * m2 - os_ ** 2)
        L.mc(P, "a: the linear posterior moment is unbiased for E[o*^2]", f"s={s}, sigma_eta={t}", 0.0, v, se)
        # Gaussian conditional second moment: regress o*^2 on o^2 (slope b^2, intercept (1-b) s^2)
        X = np.column_stack([np.ones(n), o * o])
        coef = np.linalg.lstsq(X, os_ ** 2, rcond=None)[0]
        resid = os_ ** 2 - X @ coef
        cov = np.linalg.inv(X.T @ X) * np.mean(resid ** 2)
        L.mc(P, "a: Gaussian E[o*^2 | o] has slope b^2 on o^2", f"s={s}, sigma_eta={t}", b * b, coef[1],
             math.sqrt(cov[1, 1]))
        L.mc(P, "a: Gaussian E[o*^2 | o] has intercept b(1-b)E[o^2]", f"s={s}, sigma_eta={t}", b * (1 - b) * m2,
             coef[0], math.sqrt(cov[0, 0]))
    for theta in (0.5, 2.0):
        os_ = rng.normal(0, 1.0, n)
        o = (1 + theta) * os_
        b = float(np.mean(o * os_) / np.mean(o * o))
        L.ident(P, "a: proportional overreaction makes (b o)^2 = o*^2 pathwise", f"theta={theta}",
                0.0, float(np.max(np.abs((b * o) ** 2 - os_ ** 2))), tol=1e-9)
    # the deficit is not identified: two laws with the same (o, r) law, different E[o*^2]
    moo, mrr, b = 1.0, 2.0, 0.4
    low, high = b * b * moo, mrr
    L.holds(P, "a: (b o)^2 has the same mean under every law of Prop. 1(e)", "E[o^2]=1, E[r^2]=2, b=0.4",
            b * b * moo, b * b * moo, True, "E[(b o)^2] = b^2 E[o^2] depends only on the law of (o, r)")
    L.holds(P, "a: the deficit spans [0, E[r^2] - b^2 E[o^2]]", "E[o^2]=1, E[r^2]=2, b=0.4", high - low,
            high - low, high > low, "E[o*^2] - b^2 E[o^2] = 0 and = E[r^2] - b^2 E[o^2] are both attained")

    # (b) the extended range, pathwise ------------------------------------------------------------
    o = rng.normal(0, 0.02, n)
    c = rng.normal(0, 0.02, n)
    u = np.maximum(0, c) + rng.exponential(0.01, n)
    d = np.minimum(0, c) - rng.exponential(0.01, n)
    h, l = o + u, o + d
    for bval in (0.0, 0.3, 0.7, 1.0):
        bo = bval * o
        Rs = (u - d) + np.maximum(0, bo - h) + np.maximum(0, l - bo)
        alt = np.maximum(h, bo) - np.minimum(l, bo)
        TR = np.maximum(h, 0) - np.minimum(l, 0)
        L.ident(P, "b: R* = max(h, b o) - min(l, b o)", f"b={bval}, {n} bars", 0.0, float(np.max(np.abs(Rs - alt))),
                tol=1e-12)
        L.holds(P, "b: R <= R* <= TR", f"b={bval}, {n} bars", 0.0,
                float(np.sum((Rs < (u - d) - 1e-15) | (Rs > TR + 1e-15))),
                bool(np.all((Rs >= (u - d) - 1e-15) & (Rs <= TR + 1e-15))), "violations = 0")
    L.ident(P, "b: R* = R when b = 1", f"{n} bars", 0.0,
            float(np.max(np.abs((np.maximum(h, o) - np.minimum(l, o)) - (u - d)))), tol=1e-12)
    ex = math.log(1.05)
    ex_kernel = (1 - LAM0) * ex ** 2 / (4 * LN2)
    L.ident(P, "b: the audit's bar gives R* = ln(O/C_-)", "C_- = C = L = 100, O = H = 105, b = 0", ex,
            float(np.maximum(ex, 0.0) - np.minimum(0.0, 0.0)))
    N.put("k7-ex-kernel", ex_kernel * 1e4, nd=2)

    # (c) the meander law and the loading -----------------------------------------------------------
    EU = meander_mean()
    L.numeric(P, "c: E[U] = sqrt(2 pi) ln 2 from the meander law", "integral of 1 - F_U", SQ2PI * LN2, EU, tol=1e-9)
    N.put("k7-EU", EU, nd=4)
    for x in (0.5, 1.0, 1.5, 2.0, 3.0):
        L.numeric(P, "c: the meander law is the images limit of (-m | M < a)", f"x={x}, a=1e-4",
                  meander_cdf(x), meander_cdf_from_images(x), tol=2e-4)
        if x >= 1.0:
            k = np.arange(1, 61)
            L.numeric(P, "c: both forms of the meander law agree", f"x={x}", meander_cdf(x),
                      float(2.0 * SQ2PI / x * np.sum(np.exp(-((2 * np.arange(60) + 1) ** 2) * math.pi ** 2 / (2 * x * x)))),
                      tol=1e-12)
            _ = k
    grid = np.linspace(0.05, 6.0, 60)
    g = np.array([gamma_tr(s) for s in grid])
    L.holds(P, "c: gamma_TR is increasing in s", "s in [0.05, 6], 60 points", float(np.min(np.diff(g))), 0.0,
            bool(np.all(np.diff(g) > 0)), "min increment > 0")
    lo = np.maximum(0.25, grid / (4 * math.pi * LN2))
    hi = 0.25 + grid / (4 * math.pi * LN2)
    L.holds(P, "c: max(1/4, s/(4 pi ln 2)) <= gamma_TR <= 1/4 + s/(4 pi ln 2)", "s in [0.05, 6], 60 points",
            float(np.min(np.minimum(g - lo, hi - g))), 0.0, bool(np.all((g >= lo - 1e-12) & (g <= hi + 1e-12))),
            "both margins >= 0")
    L.numeric(P, "c: gamma_TR -> 1/4 as s -> 0", "s = 1e-3", 0.25, gamma_tr(1e-3), tol=1e-6)
    L.numeric(P, "c: gamma_TR - s/(4 pi ln 2) -> 0 as s -> infinity", "s = 200", 0.0,
              gamma_tr(200.0) - 200.0 / (4 * math.pi * LN2), tol=5e-3)
    for s in (0.25, 0.5, 1.0, 2.0, 4.0):
        L.numeric(P, "c: two routes to gamma_TR agree", f"s={s}", gamma_tr(s), gamma_tr_direct(s), tol=2e-4)
    for s in (0.3, 0.5, 1.0, 2.0):
        key = str(s).replace(".", "p")
        N.put(f"k7-gTR-{key}", gamma_tr(s), nd=3)
        N.put(f"k7-gOF-{key}", (1 - LAM0) * gamma_tr(s), nd=3)

    # first-order loadings against simulation: paired draws, extrapolated linearly in rho to zero
    D, M, m = brownian_bars(n, steps, rng)
    Z1, Z2 = rng.standard_normal(n), rng.standard_normal(n)
    rhos = (0.02, 0.04, 0.08)
    names = ("Parkinson", "true-range Parkinson TR^2/(4 ln 2)", "open-free kernel", "full kernel",
             "full kernel, posterior overnight term", "overnight^2 + Parkinson")
    for s in (0.5, 1.0, 2.0):
        fits = {name: ([], []) for name in names}
        for rho in rhos:
            ks = kernels(s * Z1, rho * Z2, M, m, D, s, rho)
            for name in names:
                v, se = batch_mean((ks[name][0] - ks[name][1]) / rho ** 2)
                fits[name][0].append(v)
                fits[name][1].append(se)
            del ks
        for name in names:
            est, ses = fits[name]
            # weighted least squares of the loading on rho; the intercept is the first-order loading
            Wt = 1.0 / np.square(ses)
            X = np.column_stack([np.ones(3), rhos])
            A = X.T @ (X * Wt[:, None])
            beta = np.linalg.solve(A, X.T @ (Wt * np.array(est)))
            se0 = math.sqrt(np.linalg.inv(A)[0, 0])
            L.mc(P, f"c: first-order loading of the {name}", f"s={s}, rho={rhos}, {n} paths, {steps} steps",
                 FIRST_ORDER[name](s), beta[0], se0)
    return dict(D=D, M=M, m=m, Z1=Z1, Z2=Z2)


