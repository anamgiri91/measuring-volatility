def part_b(draws: dict) -> pd.DataFrame:
    rows = []
    for s in (0.3, 0.5, 1.0, 2.0):
        for rho in (0.25, 0.5, 1.0):
            ks = kernels(s * draws["Z1"], rho * draws["Z2"], draws["M"], draws["m"], draws["D"], s, rho)
            for name, (k, k0) in ks.items():
                v, se = batch_mean((k - k0) / rho ** 2)
                rows.append(dict(part="B", sample="Assumption 2", s=s, rho=rho, kernel=name,
                                 first_order_loading=FIRST_ORDER[name](s), exact_loading=v, se=se,
                                 relative_bias=float(np.mean(k - k0) / np.mean(k0))))
    return pd.DataFrame(rows)


# =============================================================================================
# Part C: the scales the data imply, under an uncorrelated error
# =============================================================================================

def implied(b: float, ratio: float) -> tuple[float, float]:
    """(s, rho) from b and E[o^2]/E[c^2] when E[o* eta] = 0 and closing errors are zero:
    sigma_eta^2 = (1 - b) E[o^2], sigma_c^2 = E[c^2] - sigma_eta^2, E[o*^2] = b E[o^2]."""
    x = (1.0 - b) * ratio
    s2 = b * ratio / (1.0 - x)
    return math.sqrt(s2), math.sqrt(x / (1.0 - x))


def part_c(draws: dict) -> pd.DataFrame:
    rows = []
    ap = pd.read_csv(TAB / "table122_theory_applications.csv")
    for reg in ("A1", "B", "A2", "C"):
        x = ap[(ap.part == "B1") & (ap["sample"] == f"NEPSE {reg}")].set_index("statistic")["value"]
        rows.append((f"NEPSE {reg}", float(x["b"]), float(x["E[o^2]/E[OC]"])))
    x = ap[(ap.part == "B1") & ap["sample"].str.startswith("NIFTY")].set_index("statistic")["value"]
    rows.append(("NIFTY 50", float(x["b"]), float(x["E[o^2]/E[OC]"])))
    if INPUTS.exists():
        from nepsevol import frontier as F
        for name in list(F.SPANS) + list(F.SPANS_M18):
            p, _ = F.market_panel(name, INPUTS)
            b = float((p["o"] * p["r"]).sum() / (p["o"] ** 2).sum())
            rows.append((name, b, float((p["o"] ** 2).mean() / (p["c"] ** 2).mean())))
    out = []
    for name, b, ratio in rows:
        if not (0 < b < 1):
            out.append(dict(part="C", sample=name, b=b, ratio=ratio, s=np.nan, rho=np.nan))
            continue
        s, rho = implied(b, ratio)
        row = dict(part="C", sample=name, b=b, ratio=ratio, s=s, rho=rho, gamma_TR=gamma_tr(s),
                   gamma_open_free=(1 - LAM0) * gamma_tr(s))
        # the exact exposures at this sample's own (s, rho)
        ks = kernels(s * draws["Z1"], rho * draws["Z2"], draws["M"], draws["m"], draws["D"], s, rho)
        for name_k, key in (("Parkinson", "exact_P"), ("open-free kernel", "exact_open_free"),
                            ("full kernel", "exact_full"), ("overnight^2 + Parkinson", "exact_o2P")):
            k, k0 = ks[name_k]
            row[key] = float(np.mean(k - k0) / rho ** 2)
        out.append(row)
    return pd.DataFrame(out)


