def fmt(v, nd=3):
    s = f"{abs(v):.{nd}f}"
    return (r"\ensuremath{-}" + s) if v < 0 and float(s) != 0 else s


def write_table(N: Numbers, B: pd.DataFrame) -> None:
    order = ["close-to-close r^2", "Parkinson", "true-range Parkinson TR^2/(4 ln 2)", "open-free kernel",
             "full kernel", "full kernel, posterior overnight term", "overnight^2 + Parkinson"]
    label = {"close-to-close r^2": r"close-to-close $r^2$", "Parkinson": r"Parkinson $R^2/(4\ln2)$",
             "true-range Parkinson TR^2/(4 ln 2)": r"true range $TR^2/(4\ln2)$",
             "open-free kernel": r"open-free kernel $A_0$", "full kernel": r"full kernel $A$",
             "full kernel, posterior overnight term": r"$A$ with $\pi(o)$ for $(b o)^2$",
             "overnight^2 + Parkinson": r"$o^2+P$"}
    lines = []
    for name in order:
        cells = [label[name]]
        for s in (0.3, 1.0):
            cells.append(fmt(FIRST_ORDER[name](s)))
            for rho in (0.5, 1.0):
                r = B[(B.kernel == name) & (B.s == s) & (B.rho == rho)].iloc[0]
                cells.append(fmt(r.exact_loading))
        lines.append(" & ".join(cells) + r" \\")
    (GEN / "tab_kernel.tex").write_text("\n".join(lines) + "\n")
    for name, key in (("Parkinson", "P"), ("open-free kernel", "OF"), ("full kernel", "full"),
                      ("full kernel, posterior overnight term", "post")):
        for s in (0.3, 1.0):
            for rho in (0.5, 1.0):
                r = B[(B.kernel == name) & (B.s == s) & (B.rho == rho)].iloc[0]
                N.put(f"k7-ex-{key}-s{str(s).replace('.', 'p')}-r{str(rho).replace('.', 'p')}", r.exact_loading)


