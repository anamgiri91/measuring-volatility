def part_c(N: Numbers) -> pd.DataFrame:
    if not INPUTS.exists():
        sys.exit("data/external/frontier/ is missing: see data/external/README.md (Part C needs it)")
    s44 = _load("s44_m19", "44_anam_recheck.py")
