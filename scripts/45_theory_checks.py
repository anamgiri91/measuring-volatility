    def stats(ii, w):
        if w.sum() == 0:
            return [np.nan] * 5
        o2 = (w * o[ii] ** 2).sum()
        b = (w * o[ii] * r[ii]).sum() / o2
        q = o2 / (w * OC[ii]).sum()
        ga = ((math.sqrt(5 - 4 * b) - 1) / 2) ** 2 if b < 1 else 0.0
        return [b, q, (1 - b) ** 2 * q if b < 1 else 0.0, ga * q, (1 - b) * q]

