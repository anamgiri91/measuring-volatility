"""Checks of Proposition 8 of the theory supplement: the market-implied open.

Derived during the development of Anam II (``ANAM2_DEVELOPMENT.md``), from its descriptive round E0, and written
after plan M22 was frozen. It predicts nothing that M22 tests, and no verdict depends on it.

Part A  Every closed form, identity and inequality of Proposition 8 is set against a simulation, a numerical
        computation or a pathwise identity (ledger: table143):
        (a) the leave-one-out market move carries none of the security's own opening error;
        (b) its sampling error has second moment V_N = (N-1)^-2 sum_{j != i} E[(zeta_j + eta_j)^2];
        (c) E[m^2] = beta_bar^2 sigma_f^2 + V_N, and the pooled projection of r on m;
        (d) b = mu + (1 - mu) b_I in the population, and exactly mu_hat b_M_hat + (1 - mu_hat) b_I_hat in a
            sample when the market move is the inclusive cross-sectional mean;
        (e) the kernel on a stale bar and on a bar whose open moved;
        (f) lambda_n, the expected squared range of n equally spaced observations from the anchor: 1 at n = 1,
            increasing, tending to 4 ln 2.
Part B  The data, on each panel's training span (table144): b, its market and stock-specific parts, the market's
        share of the overnight second moment, the attenuation of the leave-one-out projection that (c) predicts
        from the cross-sectional dispersion, and the shares of stale opens and one-price bars.

Every number the LaTeX quotes is written as a macro to paper/theory/generated/market_open.tex, and the data table
to generated/tab_market_open.tex.

Usage
    python scripts/54_market_open_theory.py            # Parts A and B (Part B reads the frontier panels)
    python scripts/54_market_open_theory.py --quick    # Part A with smaller simulations, no Part B
"""
